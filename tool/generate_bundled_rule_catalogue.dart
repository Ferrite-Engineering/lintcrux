// Writes lib/services/rules/bundled_rule_catalogue.dart from the rule
// databases in lib/data/rules/<engineId>.json.
//
// The desktop app reads those files from its asset bundle; the headless
// binary has none, so `lintcrux rule` reads this compiled-in copy of the one
// fact it needs beyond the help link: each rule's default severity.
// test/static/bundled_rule_catalogue_test.dart holds the two equal, rule by
// rule, through the app's own parser.
//
// Run from the lintcrux package root:
//
//   dart run tool/generate_bundled_rule_catalogue.dart
import 'dart:convert';
import 'dart:io';

const String _out = 'lib/services/rules/bundled_rule_catalogue.dart';

void main() {
  final dir = Directory('lib/data/rules');
  final files =
      dir
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final entries = <String>[];
  for (final file in files) {
    final doc = jsonDecode(file.readAsStringSync()) as Map<String, Object?>;
    final engine = doc['engineId']! as String;
    for (final rule in doc['rules']! as List<Object?>) {
      if (rule is! Map<String, Object?>) continue;
      final id = rule['id'];
      final severity = rule['defaultSeverity'];
      if (id is! String || severity is! String) continue;
      final name = switch (severity.toLowerCase()) {
        'info' || 'note' => 'note',
        final s => s,
      };
      entries.add("  '$engine/$id': '$name',");
    }
  }
  final out = StringBuffer()
    ..writeln('// Copyright 2026 Ferrite Engineering LLC')
    ..writeln('// SPDX-License-Identifier: Apache-2.0')
    ..writeln()
    ..writeln('// Generated by tool/generate_bundled_rule_catalogue.dart from')
    ..writeln('// lib/data/rules/*.json. Do not edit by hand.')
    ..writeln()
    ..writeln('/// Every rule the bundled rule databases list, by its')
    ..writeln('/// engine-namespaced id, with its default severity')
    ..writeln(
      "/// (`Severity.name`). The headless binary's copy of what the app",
    )
    ..writeln('/// reads from its asset bundle; see')
    ..writeln('/// `test/static/bundled_rule_catalogue_test.dart`.')
    ..writeln(
      'const Map<String, String> kBundledRuleSeverities = '
      '<String, String>{',
    )
    ..writeAll(entries, '\n')
    ..writeln()
    ..writeln('};');
  File(_out).writeAsStringSync(out.toString());
  stdout.writeln('wrote ${entries.length} rules to $_out');
}
